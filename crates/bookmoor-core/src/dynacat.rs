//! Renders the canonical tree as a Dynacat `bookmarks` widget.
//!
//! The output is a self-contained YAML file meant to be pulled into the
//! Dynacat config with `- $include: bookmoor.yml` (see
//! `docs/adapters/dynacat.md`). It is generated from scratch on every write,
//! so there is nothing to merge and no entry identity to preserve.
//!
//! Dynacat groups are flat, so folders are mapped like this:
//! - bookmarks directly under the root form a leading group without title,
//! - every folder becomes a group titled with its path (`Parent / Child`),
//!   listed depth first in sibling order,
//! - folders without any usable bookmark are left out,
//! - only `http` and `https` URLs are written (`javascript:`, `chrome:` and
//!   the like would be dead or dangerous links on a dashboard).

use crate::model::Kind;
use crate::wire::WireNode;
use std::collections::BTreeMap;

/// Header of the generated file; also tells people not to edit it.
pub const HEADER: &str = "# Generated by bookmoor. Changes made here are overwritten.\n";

const EMPTY_GROUPS: &str = "groups:\n  - title: \"No bookmarks yet\"\n    links: []\n";

fn empty_widget() -> String {
    format!("{HEADER}type: bookmarks\n{EMPTY_GROUPS}")
}

/// Folders nested deeper than this are not rendered (keeps the recursion and
/// the path titles bounded).
const MAX_DEPTH: usize = 32;

/// Group title (none for the leading one) and its `(title, url)` links.
type Groups = Vec<(Option<String>, Vec<(String, String)>)>;

/// How a group is titled.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum GroupNames {
    /// The whole path, `toolbar / Dev / Rust` (default, never ambiguous).
    #[default]
    Path,
    /// Only the folder's own name, `Rust` (shorter, can repeat).
    Name,
}

/// Looks of the generated widget. The default is the plain output of
/// [`render_widget`]; every option only changes how things are shown.
#[derive(Debug, Clone, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(default)]
pub struct Style {
    /// Widget title shown above the bookmarks (tells pages or profiles apart).
    pub title: Option<String>,
    /// Group titles: full path or just the folder name.
    pub names: GroupNames,
    /// Deepest folder level (below the chosen folder) that gets a group of
    /// its own; bookmarks of deeper folders join the group of their ancestor
    /// at that level. `None` = no limit. Fewer groups, longer ones.
    pub depth: Option<usize>,
    /// Cut link titles longer than this many characters (with `…`).
    pub max_title: Option<usize>,
    /// Ask for the site icon (`https://HOST/favicon.ico`) of every link. The
    /// browser showing the dashboard then contacts each site.
    pub icons: bool,
    /// No arrow behind the links.
    pub hide_arrow: bool,
    /// Open links in the same tab.
    pub same_tab: bool,
}

impl Style {
    /// The longest title Bookmoor accepts for the widget.
    pub const MAX_TITLE: usize = 80;

    /// Reject values that would make a useless or odd widget.
    pub fn check(&self) -> Result<(), String> {
        if let Some(t) = &self.title {
            if t.trim().is_empty() || t.chars().count() > Self::MAX_TITLE || t.contains(';') {
                return Err(format!(
                    "title: 1 to {} characters, no semicolon",
                    Self::MAX_TITLE
                ));
            }
        }
        if self.depth.is_some_and(|d| d > MAX_DEPTH) {
            return Err(format!("depth: at most {MAX_DEPTH}"));
        }
        if self.max_title.is_some_and(|m| !(8..=500).contains(&m)) {
            return Err("max title length: between 8 and 500 characters".into());
        }
        Ok(())
    }
}

/// Cut `s` to at most `max` characters, ending in `…` when shortened.
fn shorten(s: &str, max: usize) -> String {
    if s.chars().count() <= max {
        return s.to_string();
    }
    let mut t: String = s.chars().take(max - 1).collect();
    while t.ends_with(char::is_whitespace) {
        t.pop();
    }
    t.push('…');
    t
}

/// Render `nodes` (any order, as returned by `GET /v1/tree`) as widget YAML.
pub fn render_widget(nodes: &[WireNode]) -> String {
    render_folder(nodes, &[]).unwrap_or_else(empty_widget)
}

/// Every folder that `render_folder` can select, as title paths from the root
/// (depth first, sibling order). Folders whose title contains `/` are left
/// out, as are their descendants: a `/`-separated spec cannot name them.
pub fn folder_paths(nodes: &[WireNode]) -> Vec<Vec<String>> {
    let mut kids: BTreeMap<&str, Vec<&WireNode>> = BTreeMap::new();
    let mut root = None;
    for n in nodes {
        match &n.parent {
            Some(p) => kids.entry(p.as_str()).or_default().push(n),
            None => root = Some(n),
        }
    }
    for list in kids.values_mut() {
        list.sort_by(|a, b| (&a.position, &a.id).cmp(&(&b.position, &b.id)));
    }
    fn walk(
        kids: &BTreeMap<&str, Vec<&WireNode>>,
        id: &str,
        path: &mut Vec<String>,
        out: &mut Vec<Vec<String>>,
    ) {
        if path.len() >= MAX_DEPTH {
            return;
        }
        for c in kids.get(id).map(Vec::as_slice).unwrap_or(&[]) {
            if c.kind != Kind::Folder || c.title.contains('/') {
                continue;
            }
            path.push(match c.title.trim() {
                "" => "(unnamed)".to_string(),
                t => t.to_string(),
            });
            out.push(path.clone());
            walk(kids, &c.id, path, out);
            path.pop();
        }
    }
    let mut out = Vec::new();
    if let Some(root) = root {
        walk(&kids, &root.id, &mut Vec::new(), &mut out);
    }
    out
}

/// Like [`render_widget`], but only the folder reached by `folder` (titles
/// from the root, compared trimmed and case-insensitively; empty = the whole
/// tree). The folder's own bookmarks form the untitled leading group and its
/// subfolders are titled relative to it. Of several sibling folders with the
/// same title the first in sibling order is taken. `None` when the folder (or the
/// root) does not exist.
pub fn render_folder(nodes: &[WireNode], folder: &[&str]) -> Option<String> {
    render_styled(nodes, folder, &Style::default())
}

/// [`render_folder`] with a [`Style`].
pub fn render_styled(nodes: &[WireNode], folder: &[&str], style: &Style) -> Option<String> {
    let mut kids: BTreeMap<&str, Vec<&WireNode>> = BTreeMap::new();
    let mut root = None;
    for n in nodes {
        match &n.parent {
            Some(p) => kids.entry(p.as_str()).or_default().push(n),
            None => root = Some(n),
        }
    }
    for list in kids.values_mut() {
        list.sort_by(|a, b| (&a.position, &a.id).cmp(&(&b.position, &b.id)));
    }
    let mut start = root?;
    for want in folder {
        // An untitled folder is shown as "(unnamed)", so it is selected so.
        let want = want.trim().to_lowercase();
        let title_of = |c: &WireNode| match c.title.trim() {
            "" => "(unnamed)".to_string(),
            t => t.to_lowercase(),
        };
        let kids_of = kids
            .get(start.id.as_str())
            .map(Vec::as_slice)
            .unwrap_or(&[]);
        start = kids_of
            .iter()
            .find(|c| c.kind == Kind::Folder && title_of(c) == want)?;
    }
    let mut groups: Groups = Vec::new();
    collect(&kids, start, None, 0, style, &mut groups);

    let mut out = String::from(HEADER);
    out.push_str("type: bookmarks\n");
    if let Some(t) = style
        .title
        .as_deref()
        .map(str::trim)
        .filter(|t| !t.is_empty())
    {
        out.push_str(&format!("title: {}\n", scalar(t)));
    }
    if groups.is_empty() {
        out.push_str(EMPTY_GROUPS);
        return Some(out);
    }
    out.push_str("groups:\n");
    for (title, links) in &groups {
        let mut lead = "  - ";
        if let Some(t) = title {
            out.push_str(&format!("  - title: {}\n", scalar(t)));
            lead = "    ";
        }
        out.push_str(&format!("{lead}links:\n"));
        for (t, u) in links {
            let t = match style.max_title {
                Some(m) => shorten(t, m),
                None => t.clone(),
            };
            out.push_str(&format!(
                "      - title: {}\n        url: {}\n",
                scalar(&t),
                scalar(u)
            ));
            if style.icons {
                if let Some(i) = icon_url(u) {
                    out.push_str(&format!("        icon: {}\n", scalar(&i)));
                }
            }
            if style.hide_arrow {
                out.push_str("        hide-arrow: true\n");
            }
            if style.same_tab {
                out.push_str("        same-tab: true\n");
            }
        }
    }
    Some(out)
}

/// Depth-first: the folder's own bookmarks become one group, then each
/// subfolder follows.
fn collect(
    kids: &BTreeMap<&str, Vec<&WireNode>>,
    folder: &WireNode,
    path: Option<&str>,
    depth: usize,
    style: &Style,
    groups: &mut Groups,
) {
    let children = kids
        .get(folder.id.as_str())
        .map(Vec::as_slice)
        .unwrap_or(&[]);
    let mut links = own_links(children);
    // At the depth limit the folders below join this group.
    let merge = style.depth.is_some_and(|d| depth >= d);
    if merge {
        fn all(
            kids: &BTreeMap<&str, Vec<&WireNode>>,
            id: &str,
            left: usize,
            out: &mut Vec<(String, String)>,
        ) {
            if left == 0 {
                return;
            }
            for c in kids.get(id).map(Vec::as_slice).unwrap_or(&[]) {
                if c.kind == Kind::Folder {
                    let kids_of = kids.get(c.id.as_str()).map(Vec::as_slice).unwrap_or(&[]);
                    out.extend(own_links(kids_of));
                    all(kids, &c.id, left - 1, out);
                }
            }
        }
        all(kids, &folder.id, MAX_DEPTH - depth, &mut links);
    }
    if !links.is_empty() {
        groups.push((path.map(str::to_string), links));
    }
    if merge || depth >= MAX_DEPTH {
        return;
    }
    for c in children.iter().filter(|c| c.kind == Kind::Folder) {
        let name = match c.title.trim() {
            "" => "(unnamed)",
            n => n,
        };
        let sub = match (path, style.names) {
            (Some(p), GroupNames::Path) => format!("{p} / {name}"),
            _ => name.to_string(),
        };
        collect(kids, c, Some(&sub), depth + 1, style, groups);
    }
}

/// The http(s) bookmarks among `children`, as `(title, url)`.
fn own_links(children: &[&WireNode]) -> Vec<(String, String)> {
    children
        .iter()
        .filter(|c| c.kind == Kind::Bookmark)
        .filter_map(|c| {
            let url = c.url.as_deref()?.trim();
            let lower = url.to_ascii_lowercase();
            if !(lower.starts_with("http://") || lower.starts_with("https://")) {
                return None;
            }
            let title = if c.title.trim().is_empty() {
                url
            } else {
                c.title.trim()
            };
            Some((title.to_string(), url.to_string()))
        })
        .collect()
}

/// `https://host[:port]/favicon.ico` for a http(s) URL.
fn icon_url(url: &str) -> Option<String> {
    let (scheme, rest) = url.split_once("://")?;
    let host = rest.split(['/', '?', '#']).next()?;
    // Credentials in the URL must never end up in a second URL.
    if host.is_empty() || host.contains('@') {
        return None;
    }
    Some(format!("{scheme}://{host}/favicon.ico"))
}

/// A YAML double-quoted scalar. JSON string syntax is valid YAML, and
/// quoting everything keeps `yes`, `1e3`, `#` and `: ` from being misread.
fn scalar(s: &str) -> String {
    // JSON leaves these unescaped, but YAML rejects DEL and folds the
    // Unicode line breaks.
    let json = serde_json::to_string(s).expect("strings serialise");
    let mut out = String::with_capacity(json.len());
    for c in json.chars() {
        match c {
            '\u{7f}' | '\u{85}' | '\u{2028}' | '\u{2029}' => {
                out.push_str(&format!("\\u{:04x}", c as u32))
            }
            c => out.push(c),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn node(
        id: &str,
        parent: Option<&str>,
        pos: &str,
        kind: Kind,
        title: &str,
        url: Option<&str>,
    ) -> WireNode {
        WireNode {
            id: id.into(),
            parent: parent.map(Into::into),
            position: pos.into(),
            kind,
            title: title.into(),
            url: url.map(Into::into),
        }
    }

    fn sample() -> Vec<WireNode> {
        vec![
            node("root", None, "", Kind::Folder, "Bookmarks", None),
            node("bar", Some("root"), "a", Kind::Folder, "Bar", None),
            node(
                "b2",
                Some("bar"),
                "b",
                Kind::Bookmark,
                "Second",
                Some("https://two.example"),
            ),
            node(
                "b1",
                Some("bar"),
                "a",
                Kind::Bookmark,
                "First: \"one\"",
                Some("https://one.example/?a=1#x"),
            ),
            node("dev", Some("bar"), "c", Kind::Folder, "Dev", None),
            node(
                "d1",
                Some("dev"),
                "a",
                Kind::Bookmark,
                "",
                Some("http://dev.example"),
            ),
            node(
                "js",
                Some("dev"),
                "b",
                Kind::Bookmark,
                "Evil",
                Some("javascript:alert(1)"),
            ),
            node("empty", Some("bar"), "d", Kind::Folder, "Empty", None),
            node("other", Some("root"), "b", Kind::Folder, "Other", None),
        ]
    }

    #[test]
    fn style_options_shape_the_widget() {
        let st = Style {
            title: Some("Work".into()),
            names: GroupNames::Name,
            depth: Some(1),
            max_title: Some(8),
            icons: true,
            hide_arrow: true,
            same_tab: true,
        };
        st.check().unwrap();
        let y = render_styled(&sample(), &["Bar"], &st).unwrap();
        // Bar's own links lead; its subfolder Dev is at the depth limit.
        assert!(
            y.contains("type: bookmarks\ntitle: \"Work\"\ngroups:"),
            "{y}"
        );
        assert!(y.contains("title: \"First:…\""), "{y}");
        assert!(y.contains("icon: \"https://one.example/favicon.ico\""));
        assert!(y.contains("hide-arrow: true") && y.contains("same-tab: true"));
        assert!(y.contains("  - title: \"Dev\"\n"), "{y}");
        // Depth 0: everything under the folder in one untitled group.
        let flat = Style {
            depth: Some(0),
            ..Style::default()
        };
        let y = render_styled(&sample(), &["Bar"], &flat).unwrap();
        assert_eq!(y.matches("links:").count(), 1, "{y}");
        assert!(y.contains("http://dev.example") && !y.contains("javascript"));
        // The default style is the plain output.
        assert_eq!(
            render_styled(&sample(), &[], &Style::default()),
            render_folder(&sample(), &[])
        );
        assert!(Style {
            title: Some("a;b".into()),
            ..Style::default()
        }
        .check()
        .is_err());
        assert!(Style {
            max_title: Some(2),
            ..Style::default()
        }
        .check()
        .is_err());
    }

    #[test]
    fn icon_urls_never_carry_credentials() {
        assert_eq!(
            icon_url("https://a.example:8443/x?y#z").unwrap(),
            "https://a.example:8443/favicon.ico"
        );
        assert!(icon_url("https://user:pw@a.example/").is_none());
    }

    #[test]
    fn groups_follow_folders_in_sibling_order() {
        let y = render_widget(&sample());
        let expected = "# Generated by bookmoor. Changes made here are overwritten.\n\
type: bookmarks\n\
groups:\n\
\x20 - title: \"Bar\"\n\
\x20   links:\n\
\x20     - title: \"First: \\\"one\\\"\"\n\
\x20       url: \"https://one.example/?a=1#x\"\n\
\x20     - title: \"Second\"\n\
\x20       url: \"https://two.example\"\n\
\x20 - title: \"Bar / Dev\"\n\
\x20   links:\n\
\x20     - title: \"http://dev.example\"\n\
\x20       url: \"http://dev.example\"\n";
        assert_eq!(y, expected);
    }

    #[test]
    fn root_level_bookmarks_form_an_untitled_group() {
        let nodes = vec![
            node("root", None, "", Kind::Folder, "Bookmarks", None),
            node(
                "x",
                Some("root"),
                "a",
                Kind::Bookmark,
                "X",
                Some("https://x.example"),
            ),
        ];
        let y = render_widget(&nodes);
        assert!(
            y.contains("groups:\n  - links:\n      - title: \"X\""),
            "{y}"
        );
    }

    #[test]
    fn awkward_titles_are_escaped_or_named() {
        let nodes = vec![
            node("root", None, "", Kind::Folder, "Bookmarks", None),
            node("f", Some("root"), "a", Kind::Folder, "  ", None),
            node(
                "x",
                Some("f"),
                "a",
                Kind::Bookmark,
                "a\u{2028}b\u{7f}",
                Some("https://x.example"),
            ),
        ];
        let y = render_widget(&nodes);
        assert!(y.contains("title: \"(unnamed)\""), "{y}");
        assert!(y.contains("\"a\\u2028b\\u007f\""), "{y}");
    }

    #[test]
    fn a_folder_can_be_rendered_on_its_own() {
        let y = render_folder(&sample(), &["bar"]).unwrap();
        // Its own bookmarks first (untitled), subfolders relative to it.
        assert!(
            y.contains("groups:\n  - links:\n      - title: \"First"),
            "{y}"
        );
        assert!(y.contains("  - title: \"Dev\"\n"), "{y}");
        assert!(!y.contains("Bar / Dev"), "{y}");
        let y = render_folder(&sample(), &["Bar", " dev "]).unwrap();
        assert!(
            y.contains("groups:\n  - links:\n      - title: \"http://dev.example"),
            "{y}"
        );
        assert!(render_folder(&sample(), &["nope"]).is_none());
        assert!(render_folder(&sample(), &["Bar", "First"]).is_none());
    }

    #[test]
    fn folder_paths_list_selectable_folders() {
        let mut nodes = sample();
        nodes.push(node("sl", Some("bar"), "e", Kind::Folder, "a/b", None));
        nodes.push(node("in", Some("sl"), "a", Kind::Folder, "Inner", None));
        let paths = folder_paths(&nodes);
        let joined: Vec<String> = paths.iter().map(|p| p.join("/")).collect();
        assert_eq!(joined, ["Bar", "Bar/Dev", "Bar/Empty", "Other"]);
        for p in &paths {
            let refs: Vec<&str> = p.iter().map(String::as_str).collect();
            assert!(render_folder(&nodes, &refs).is_some());
        }
    }

    #[test]
    fn a_missing_root_renders_the_empty_widget() {
        assert!(render_widget(&[]).contains("No bookmarks yet"));
    }

    #[test]
    fn empty_tree_still_yields_a_valid_widget() {
        let y = render_widget(&[node("root", None, "", Kind::Folder, "Bookmarks", None)]);
        assert!(y.contains("type: bookmarks"));
        assert!(y.contains("links:"));
    }

    #[test]
    fn output_is_independent_of_input_order() {
        let mut rev = sample();
        rev.reverse();
        assert_eq!(render_widget(&sample()), render_widget(&rev));
    }
}
