//! Renders the canonical tree as a Dynacat `bookmarks` widget.
//!
//! The output is a self-contained YAML file meant to be pulled into the
//! Dynacat config with `- $include: bookmoor.yml` (see
//! `docs/adapters/dynacat.md`). It is generated from scratch on every write,
//! so there is nothing to merge and no entry identity to preserve.
//!
//! Dynacat groups are flat, so folders are mapped like this:
//! - bookmarks directly under the root form a leading group without title,
//! - every folder becomes a group titled with its path (`Parent / Child`),
//!   listed depth first in sibling order,
//! - folders without any usable bookmark are left out,
//! - only `http` and `https` URLs are written (`javascript:`, `chrome:` and
//!   the like would be dead or dangerous links on a dashboard).

use crate::model::Kind;
use crate::wire::WireNode;
use std::collections::BTreeMap;

/// Header of the generated file; also tells people not to edit it.
const HEADER: &str = "# Generated by bookmoor. Changes made here are overwritten.\n";

/// Group title (none for the leading one) and its `(title, url)` links.
type Groups = Vec<(Option<String>, Vec<(String, String)>)>;

/// Render `nodes` (any order, as returned by `GET /v1/tree`) as widget YAML.
pub fn render_widget(nodes: &[WireNode]) -> String {
    let mut kids: BTreeMap<&str, Vec<&WireNode>> = BTreeMap::new();
    let mut root = None;
    for n in nodes {
        match &n.parent {
            Some(p) => kids.entry(p.as_str()).or_default().push(n),
            None => root = Some(n),
        }
    }
    for list in kids.values_mut() {
        list.sort_by(|a, b| (&a.position, &a.id).cmp(&(&b.position, &b.id)));
    }
    let mut groups: Groups = Vec::new();
    if let Some(root) = root {
        collect(&kids, root, None, &mut groups);
    }

    let mut out = String::from(HEADER);
    out.push_str("type: bookmarks\n");
    if groups.is_empty() {
        out.push_str("groups:\n  - links:\n      - title: bookmoor\n        url: \"https://github.com/swallat/bookmoor\"\n");
        return out;
    }
    out.push_str("groups:\n");
    for (title, links) in &groups {
        let mut lead = "  - ";
        if let Some(t) = title {
            out.push_str(&format!("  - title: {}\n", scalar(t)));
            lead = "    ";
        }
        out.push_str(&format!("{lead}links:\n"));
        for (t, u) in links {
            out.push_str(&format!(
                "      - title: {}\n        url: {}\n",
                scalar(t),
                scalar(u)
            ));
        }
    }
    out
}

/// Depth-first: the folder's own bookmarks become one group, then each
/// subfolder follows.
fn collect(
    kids: &BTreeMap<&str, Vec<&WireNode>>,
    folder: &WireNode,
    path: Option<&str>,
    groups: &mut Groups,
) {
    let children = kids
        .get(folder.id.as_str())
        .map(Vec::as_slice)
        .unwrap_or(&[]);
    let links: Vec<(String, String)> = children
        .iter()
        .filter(|c| c.kind == Kind::Bookmark)
        .filter_map(|c| {
            let url = c.url.as_deref()?.trim();
            let lower = url.to_ascii_lowercase();
            if !(lower.starts_with("http://") || lower.starts_with("https://")) {
                return None;
            }
            let title = if c.title.trim().is_empty() {
                url
            } else {
                c.title.trim()
            };
            Some((title.to_string(), url.to_string()))
        })
        .collect();
    if !links.is_empty() {
        groups.push((path.map(str::to_string), links));
    }
    for c in children.iter().filter(|c| c.kind == Kind::Folder) {
        let name = c.title.trim();
        let sub = match path {
            Some(p) => format!("{p} / {name}"),
            None => name.to_string(),
        };
        collect(kids, c, Some(&sub), groups);
    }
}

/// A YAML double-quoted scalar. JSON string syntax is valid YAML, and
/// quoting everything keeps `yes`, `1e3`, `#` and `: ` from being misread.
fn scalar(s: &str) -> String {
    serde_json::to_string(s).expect("strings serialise")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn node(
        id: &str,
        parent: Option<&str>,
        pos: &str,
        kind: Kind,
        title: &str,
        url: Option<&str>,
    ) -> WireNode {
        WireNode {
            id: id.into(),
            parent: parent.map(Into::into),
            position: pos.into(),
            kind,
            title: title.into(),
            url: url.map(Into::into),
        }
    }

    fn sample() -> Vec<WireNode> {
        vec![
            node("root", None, "", Kind::Folder, "Bookmarks", None),
            node("bar", Some("root"), "a", Kind::Folder, "Bar", None),
            node(
                "b2",
                Some("bar"),
                "b",
                Kind::Bookmark,
                "Second",
                Some("https://two.example"),
            ),
            node(
                "b1",
                Some("bar"),
                "a",
                Kind::Bookmark,
                "First: \"one\"",
                Some("https://one.example/?a=1#x"),
            ),
            node("dev", Some("bar"), "c", Kind::Folder, "Dev", None),
            node(
                "d1",
                Some("dev"),
                "a",
                Kind::Bookmark,
                "",
                Some("http://dev.example"),
            ),
            node(
                "js",
                Some("dev"),
                "b",
                Kind::Bookmark,
                "Evil",
                Some("javascript:alert(1)"),
            ),
            node("empty", Some("bar"), "d", Kind::Folder, "Empty", None),
            node("other", Some("root"), "b", Kind::Folder, "Other", None),
        ]
    }

    #[test]
    fn groups_follow_folders_in_sibling_order() {
        let y = render_widget(&sample());
        let expected = "# Generated by bookmoor. Changes made here are overwritten.\n\
type: bookmarks\n\
groups:\n\
\x20 - title: \"Bar\"\n\
\x20   links:\n\
\x20     - title: \"First: \\\"one\\\"\"\n\
\x20       url: \"https://one.example/?a=1#x\"\n\
\x20     - title: \"Second\"\n\
\x20       url: \"https://two.example\"\n\
\x20 - title: \"Bar / Dev\"\n\
\x20   links:\n\
\x20     - title: \"http://dev.example\"\n\
\x20       url: \"http://dev.example\"\n";
        assert_eq!(y, expected);
    }

    #[test]
    fn root_level_bookmarks_form_an_untitled_group() {
        let nodes = vec![
            node("root", None, "", Kind::Folder, "Bookmarks", None),
            node(
                "x",
                Some("root"),
                "a",
                Kind::Bookmark,
                "X",
                Some("https://x.example"),
            ),
        ];
        let y = render_widget(&nodes);
        assert!(
            y.contains("groups:\n  - links:\n      - title: \"X\""),
            "{y}"
        );
    }

    #[test]
    fn empty_tree_still_yields_a_valid_widget() {
        let y = render_widget(&[node("root", None, "", Kind::Folder, "Bookmarks", None)]);
        assert!(y.contains("type: bookmarks"));
        assert!(y.contains("links:"));
    }

    #[test]
    fn output_is_independent_of_input_order() {
        let mut rev = sample();
        rev.reverse();
        assert_eq!(render_widget(&sample()), render_widget(&rev));
    }
}
