    #[test]
    fn page_spreads_widgets_round_robin_over_columns() {
        let ws: Vec<String> = ["A", "B", "C", "D"].iter().map(|t| widget(t)).collect();
        let p = render_page("P", 3, &ws);
        let col = |size: &str| p.matches(&format!("- size: {size}")).count();
        assert_eq!((col("small"), col("full")), (2, 1));
        let pos = |t: &str| p.find(&format!("title: \"{t}\"")).unwrap();
        // Columns come in order small, full, small; A and D share the first.
        assert!(pos("A") < pos("D") && pos("D") < pos("B") && pos("B") < pos("C"));
        let two = render_page("P", 2, &ws);
        assert_eq!(two.matches("- size: full").count(), 2);
        // Out-of-range column counts are clamped.
        assert_eq!(render_page("P", 0, &ws), render_page("P", 1, &ws));
        assert_eq!(render_page("P", 9, &ws), p);
    }

