//! Renders the canonical tree as a Dynacat `bookmarks` widget.
//!
//! The output is a self-contained YAML file meant to be pulled into the
//! Dynacat config with `- $include: bookmoor.yml` (see
//! `docs/adapters/dynacat.md`). It is generated from scratch on every write,
//! so there is nothing to merge and no entry identity to preserve.
//!
//! Dynacat groups are flat, so folders are mapped like this:
//! - bookmarks directly under the root form a leading group without title,
//! - every folder becomes a group titled with its path (`Parent / Child`;
//!   see [`Style`] for short names, a depth limit, icons and more),
//!   listed depth first in sibling order,
//! - folders without any usable bookmark are left out,
//! - only `http` and `https` URLs are written (`javascript:`, `chrome:` and
//!   the like would be dead or dangerous links on a dashboard).

use crate::model::Kind;
use crate::wire::WireNode;
use std::collections::BTreeMap;

/// Header of the generated file; also tells people not to edit it.
pub const HEADER: &str = "# Generated by bookmoor. Changes made here are overwritten.\n";

const EMPTY_GROUPS: &str = "groups:\n  - title: \"No bookmarks yet\"\n    links: []\n";

fn empty_widget() -> String {
    format!("{HEADER}type: bookmarks\n{EMPTY_GROUPS}")
}

/// Folders nested deeper than this are not rendered (keeps the recursion and
/// the path titles bounded).
const MAX_DEPTH: usize = 32;

/// Group title (none for the leading one) and its `(title, url)` links.
type Groups = Vec<(Option<String>, Vec<(String, String)>)>;

/// How a group is titled.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum GroupNames {
    /// The whole path, `toolbar / Dev / Rust` (default, never ambiguous).
    #[default]
    Path,
    /// Only the folder's own name, `Rust` (shorter, can repeat).
    Name,
}

/// Looks of the generated widget. The default is the plain output of
/// [`render_widget`]; every option only changes how things are shown.
#[derive(Debug, Clone, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(default)]
pub struct Style {
    /// Widget title shown above the bookmarks (tells pages or profiles apart).
    pub title: Option<String>,
    /// Group titles: full path or just the folder name.
    pub names: GroupNames,
    /// Deepest folder level (below the chosen folder) that gets a group of
    /// its own; bookmarks of deeper folders join the group of their ancestor
    /// at that level. `None` = no limit. Fewer groups, longer ones.
    pub depth: Option<usize>,
    /// Cut link titles longer than this many characters (with `…`).
    pub max_title: Option<usize>,
    /// Ask for the site icon (`https://HOST/favicon.ico`) of every link. The
    /// browser showing the dashboard then contacts each site.
    pub icons: bool,
    /// No arrow behind the links.
    pub hide_arrow: bool,
    /// Open links in the same tab.
    pub same_tab: bool,
}

impl Style {
    /// The longest title Bookmoor accepts for the widget.
    pub const MAX_TITLE: usize = 80;

    /// Reject values that would make a useless or odd widget.
    pub fn check(&self) -> Result<(), String> {
        if let Some(t) = &self.title {
            if t.trim().is_empty() || t.chars().count() > Self::MAX_TITLE {
                return Err(format!("title: 1 to {} characters", Self::MAX_TITLE));
            }
        }
        if self.depth.is_some_and(|d| d > MAX_DEPTH) {
            return Err(format!("depth: at most {MAX_DEPTH}"));
        }
        if self.max_title.is_some_and(|m| !(8..=500).contains(&m)) {
            return Err("max title length: between 8 and 500 characters".into());
        }
        Ok(())
    }
}

/// Cut `s` to at most `max` characters, ending in `…` when shortened.
fn shorten(s: &str, max: usize) -> String {
    if s.chars().count() <= max {
        return s.to_string();
    }
    // Never trust the value (a hand-edited state file): keep room for `…`.
    let max = max.max(2);
    let mut t: String = s.chars().take(max - 1).collect();
    while t.ends_with(char::is_whitespace) {
        t.pop();
    }
    t.push('…');
    t
}

/// Render `nodes` (any order, as returned by `GET /v1/tree`) as widget YAML.
pub fn render_widget(nodes: &[WireNode]) -> String {
    render_folder(nodes, &[]).unwrap_or_else(empty_widget)
}

/// Every folder that `render_folder` can select, as title paths from the root
/// (depth first, sibling order). Folders whose title contains `/` are left
/// out, as are their descendants: a `/`-separated spec cannot name them.
pub fn folder_paths(nodes: &[WireNode]) -> Vec<Vec<String>> {
    let mut kids: BTreeMap<&str, Vec<&WireNode>> = BTreeMap::new();
    let mut root = None;
    for n in nodes {
        match &n.parent {
            Some(p) => kids.entry(p.as_str()).or_default().push(n),
            None => root = Some(n),
        }
    }
    for list in kids.values_mut() {
        list.sort_by(|a, b| (&a.position, &a.id).cmp(&(&b.position, &b.id)));
    }
    fn walk(
        kids: &BTreeMap<&str, Vec<&WireNode>>,
        id: &str,
        path: &mut Vec<String>,
        out: &mut Vec<Vec<String>>,
    ) {
        if path.len() >= MAX_DEPTH {
            return;
        }
        for c in kids.get(id).map(Vec::as_slice).unwrap_or(&[]) {
            if c.kind != Kind::Folder || c.title.contains('/') {
                continue;
            }
            path.push(match c.title.trim() {
                "" => "(unnamed)".to_string(),
                t => t.to_string(),
            });
            out.push(path.clone());
            walk(kids, &c.id, path, out);
            path.pop();
        }
    }
    let mut out = Vec::new();
    if let Some(root) = root {
        walk(&kids, &root.id, &mut Vec::new(), &mut out);
    }
    out
}

/// Like [`render_widget`], but only the folder reached by `folder` (titles
/// from the root, compared trimmed and case-insensitively; empty = the whole
/// tree). The folder's own bookmarks form the untitled leading group and its
/// subfolders are titled relative to it. Of several sibling folders with the
/// same title the first in sibling order is taken. `None` when the folder (or the
/// root) does not exist.
pub fn render_folder(nodes: &[WireNode], folder: &[&str]) -> Option<String> {
    render_styled(nodes, folder, &Style::default())
}

/// [`render_folder`] with a [`Style`].
pub fn render_styled(nodes: &[WireNode], folder: &[&str], style: &Style) -> Option<String> {
    let mut kids: BTreeMap<&str, Vec<&WireNode>> = BTreeMap::new();
    let mut root = None;
    for n in nodes {
        match &n.parent {
            Some(p) => kids.entry(p.as_str()).or_default().push(n),
            None => root = Some(n),
        }
    }
    for list in kids.values_mut() {
        list.sort_by(|a, b| (&a.position, &a.id).cmp(&(&b.position, &b.id)));
    }
    let mut start = root?;
    for want in folder {
        // An untitled folder is shown as "(unnamed)", so it is selected so.
        let want = want.trim().to_lowercase();
        let title_of = |c: &WireNode| match c.title.trim() {
            "" => "(unnamed)".to_string(),
            t => t.to_lowercase(),
        };
        let kids_of = kids
            .get(start.id.as_str())
            .map(Vec::as_slice)
            .unwrap_or(&[]);
        start = kids_of
            .iter()
            .find(|c| c.kind == Kind::Folder && title_of(c) == want)?;
    }
    let mut groups: Groups = Vec::new();
    collect(&kids, start, None, 0, style, &mut groups);

    let mut out = String::from(HEADER);
    out.push_str("type: bookmarks\n");
    if let Some(t) = style
        .title
        .as_deref()
        .map(str::trim)
        .filter(|t| !t.is_empty())
    {
        out.push_str(&format!("title: {}\n", scalar(t)));
    }
    if groups.is_empty() {
        out.push_str(EMPTY_GROUPS);
        return Some(out);
    }
    out.push_str("groups:\n");
    for (title, links) in &groups {
        let mut lead = "  - ";
        if let Some(t) = title {
            out.push_str(&format!("  - title: {}\n", scalar(t)));
            lead = "    ";
        }
        out.push_str(&format!("{lead}links:\n"));
        for (t, u) in links {
            let t = match style.max_title {
                Some(m) => shorten(t, m),
                None => t.clone(),
            };
            out.push_str(&format!(
                "      - title: {}\n        url: {}\n",
                scalar(&t),
                scalar(u)
            ));
            if style.icons {
                if let Some(i) = icon_url(u) {
                    out.push_str(&format!("        icon: {}\n", scalar(&i)));
                }
            }
            if style.hide_arrow {
                out.push_str("        hide-arrow: true\n");
            }
            if style.same_tab {
                out.push_str("        same-tab: true\n");
            }
        }
    }
    Some(out)
}

/// Most columns a Dynacat page can have.
pub const MAX_PAGE_COLUMNS: usize = 3;

/// The `size:` of each column of a page with `columns` columns (Dynacat wants
/// one or two `full` ones): `full`; `full, full`; `small, full, small`.
fn column_sizes(columns: usize) -> &'static [&'static str] {
    match columns.clamp(1, MAX_PAGE_COLUMNS) {
        1 => &["full"],
        2 => &["full", "full"],
        _ => &["small", "full", "small"],
    }
}

/// Append one page, `- name: ...`, to `out`. `widgets` are `(weight, YAML)`;
/// with `balance` each goes to the column with the least weight so far (ties:
/// the first), otherwise they go round robin. Either way the order within a
/// column follows the order given.
fn push_page(
    out: &mut String,
    name: &str,
    columns: usize,
    widgets: &[(usize, String)],
    balance: bool,
) {
    let sizes = column_sizes(columns);
    let mut cols: Vec<Vec<&String>> = vec![Vec::new(); sizes.len()];
    let mut load = vec![0usize; sizes.len()];
    for (i, (weight, w)) in widgets.iter().enumerate() {
        let c = if balance {
            (0..sizes.len()).min_by_key(|&c| (load[c], c)).unwrap_or(0)
        } else {
            i % sizes.len()
        };
        load[c] += weight + 2;
        cols[c].push(w);
    }
    out.push_str(&format!("- name: {}\n  columns:\n", scalar(name)));
    for (size, mine) in sizes.iter().zip(&cols) {
        out.push_str(&format!("    - size: {size}\n      widgets:"));
        if mine.is_empty() {
            out.push_str(" []\n");
            continue;
        }
        out.push('\n');
        for w in mine {
            let body = w.strip_prefix(HEADER).unwrap_or(w);
            for (i, line) in body.lines().enumerate() {
                out.push_str(if i == 0 { "        - " } else { "          " });
                out.push_str(line);
                out.push('\n');
            }
        }
    }
}

/// Render one Dynacat page that holds `widgets` (each as returned by
/// [`render_styled`]) inline, spread over `columns` columns (1 to 3, round
/// robin in the given order).
///
/// The page is written as a YAML list item, `- name: ...`: Dynacat's
/// `$include` replaces the whole `- $include: FILE` line (dash included) with
/// the file's text, so a page file included from `pages:` must start with the
/// dash itself.
pub fn render_page(name: &str, columns: usize, widgets: &[String]) -> String {
    let mut out = String::from(HEADER);
    let weighted: Vec<(usize, String)> = widgets.iter().map(|w| (0, w.clone())).collect();
    push_page(&mut out, name, columns, &weighted, false);
    out
}

/// Where link icons come from on a profile page.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum IconSource {
    /// No icons.
    None,
    /// Only well-known services (`di:jira`, ...): nothing is asked of other
    /// sites, Dynacat loads these from its icon set.
    #[default]
    Known,
    /// Known services, otherwise the favicon from Google
    /// (`google.com/s2/favicons`): Google learns the site names.
    Google,
    /// Known services, otherwise `https://HOST/favicon.ico`: the viewer's
    /// browser contacts every site.
    Site,
}

/// `di:` icon for a few well-known services, by their URL.
fn known_icon(url: &str) -> Option<&'static str> {
    let lower = url.to_ascii_lowercase();
    let host = host_of(&lower)?;
    // (host or parent domain, or a label of the host, icon)
    let on = |d: &str| host == d || host.ends_with(&format!(".{d}"));
    let label = |l: &str| {
        host.split('.')
            .any(|p| p == l || p.starts_with(&format!("{l}-")))
    };
    if host.ends_with("sharepoint.com") && lower.contains("/onedrive.aspx") {
        return Some("di:microsoft-onedrive");
    }
    let icon = if on("sharepoint.com") {
        "di:microsoft-sharepoint"
    } else if label("outlook") {
        "di:microsoft-outlook"
    } else if label("confluence") {
        "di:confluence"
    } else if label("jira") {
        "di:jira"
    } else if label("gitlab") || on("gitlab.com") {
        "di:gitlab"
    } else if on("github.com") {
        "di:github"
    } else if on("youtube.com") || on("youtu.be") {
        "di:youtube"
    } else if label("artifactory") {
        "di:artifactory"
    } else if label("checkmk") {
        "di:checkmk"
    } else if on("ups.com") {
        "di:ups"
    } else {
        return None;
    };
    Some(icon)
}

/// Host name of a http(s) URL (no port, no credentials).
fn host_of(url: &str) -> Option<&str> {
    let (_, rest) = url.split_once("://")?;
    let host = rest.split(['/', '?', '#']).next()?;
    if host.is_empty() || host.contains('@') {
        return None;
    }
    let host = match host.rsplit_once(':') {
        Some((h, port)) if port.chars().all(|c| c.is_ascii_digit()) => h,
        _ => host,
    };
    // Plain DNS names only: the host ends up in a query string.
    host.chars()
        .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | '_'))
        .then_some(host)
}

fn link_icon(url: &str, source: IconSource) -> Option<String> {
    if source == IconSource::None {
        return None;
    }
    if let Some(i) = known_icon(url) {
        return Some(i.to_string());
    }
    match source {
        IconSource::Google => Some(format!(
            "https://www.google.com/s2/favicons?sz=64&domain={}",
            host_of(url)?
        )),
        IconSource::Site => icon_url(url),
        _ => None,
    }
}

/// A `bookmarks` widget with one group of links, as lines without indent.
/// The widget's `title-icon` is the `di:` icon most links share (more than
/// half of them), which gives tabs and headings a recognisable mark.
fn bookmarks_widget(title: &str, links: &[(String, String)], icons: IconSource) -> String {
    let icons_of: Vec<Option<String>> = links.iter().map(|(_, u)| link_icon(u, icons)).collect();
    let mut count: BTreeMap<&str, usize> = BTreeMap::new();
    for i in icons_of.iter().flatten().filter(|i| i.starts_with("di:")) {
        *count.entry(i.as_str()).or_default() += 1;
    }
    let title_icon = count
        .into_iter()
        .max_by_key(|&(name, n)| (n, std::cmp::Reverse(name)))
        .filter(|&(_, n)| n * 2 > links.len())
        .map(|(name, _)| name);
    let mut out = format!("type: bookmarks\ntitle: {}\n", scalar(title));
    if let Some(i) = title_icon {
        out.push_str(&format!("title-icon: {}\n", scalar(i)));
    }
    out.push_str("groups:\n  - links:\n");
    for ((t, u), icon) in links.iter().zip(&icons_of) {
        out.push_str(&format!(
            "      - title: {}\n        url: {}\n",
            scalar(t),
            scalar(u)
        ));
        if let Some(i) = icon {
            out.push_str(&format!("        icon: {}\n", scalar(i)));
        }
    }
    out
}

/// Render the pages of one profile's tree: a section for every folder directly
/// under a top-level folder (`toolbar`, `other`, `mobile`), plus one for the
/// bookmarks lying loose in a top-level folder. `None` without a root.
///
/// A folder with subfolders becomes a `group` widget (tabs): its own
/// bookmarks first, then one `bookmarks` widget per subfolder, titled
/// `Folder › Sub › Subsub`. A folder without subfolders is a plain `bookmarks`
/// widget. Sections are spread over the columns by number of links, so tall
/// ones do not pile up. The result is one list item `- name: ...`.
fn profile_page(
    out: &mut String,
    name: &str,
    columns: usize,
    nodes: &[WireNode],
    icons: IconSource,
) {
    let mut kids: BTreeMap<&str, Vec<&WireNode>> = BTreeMap::new();
    let mut root = None;
    for n in nodes {
        match &n.parent {
            Some(p) => kids.entry(p.as_str()).or_default().push(n),
            None => root = Some(n),
        }
    }
    for list in kids.values_mut() {
        list.sort_by(|a, b| (&a.position, &a.id).cmp(&(&b.position, &b.id)));
    }
    fn folder_title(c: &WireNode) -> String {
        match c.title.trim() {
            "" => "(unnamed)".to_string(),
            t => t.to_string(),
        }
    }
    /// `(title, links)` of the folder and its subfolders, depth first.
    fn walk(
        kids: &BTreeMap<&str, Vec<&WireNode>>,
        folder: &WireNode,
        title: &str,
        depth: usize,
        out: &mut Vec<(String, Vec<(String, String)>)>,
    ) {
        let children = kids
            .get(folder.id.as_str())
            .map(Vec::as_slice)
            .unwrap_or(&[]);
        let links = own_links(children);
        if !links.is_empty() {
            out.push((title.to_string(), links));
        }
        if depth >= MAX_DEPTH {
            return;
        }
        for c in children.iter().filter(|c| c.kind == Kind::Folder) {
            walk(
                kids,
                c,
                &format!("{title} › {}", folder_title(c)),
                depth + 1,
                out,
            );
        }
    }
    let mut sections: Vec<(usize, String)> = Vec::new();
    let mut add = |parts: Vec<(String, Vec<(String, String)>)>| {
        let weight: usize = parts.iter().map(|(_, l)| l.len()).sum();
        let widgets: Vec<String> = parts
            .iter()
            .map(|(t, l)| bookmarks_widget(t, l, icons))
            .collect();
        match widgets.len() {
            0 => {}
            1 => sections.push((weight, widgets.into_iter().next().unwrap_or_default())),
            _ => {
                let mut g = String::from("type: group\nwidgets:\n");
                for w in &widgets {
                    for (i, line) in w.lines().enumerate() {
                        g.push_str(if i == 0 { "  - " } else { "    " });
                        g.push_str(line);
                        g.push('\n');
                    }
                }
                sections.push((weight, g));
            }
        }
    };
    if let Some(root) = root {
        let tops = kids.get(root.id.as_str()).map(Vec::as_slice).unwrap_or(&[]);
        let root_links = own_links(tops);
        if !root_links.is_empty() {
            add(vec![(folder_title(root), root_links)]);
        }
        for top in tops.iter().filter(|c| c.kind == Kind::Folder) {
            let children = kids.get(top.id.as_str()).map(Vec::as_slice).unwrap_or(&[]);
            let loose = own_links(children);
            if !loose.is_empty() {
                add(vec![(folder_title(top), loose)]);
            }
            for f in children.iter().filter(|c| c.kind == Kind::Folder) {
                let mut parts = Vec::new();
                walk(&kids, f, &folder_title(f), 1, &mut parts);
                add(parts);
            }
        }
    }
    push_page(out, name, columns, &sections, true);
}

/// Render a file with one page per `(name, tree)` of `profiles`, each laid out
/// by [`profile_page`]'s rules. Starts with [`HEADER`].
pub fn render_profile_pages(
    profiles: &[(String, Vec<WireNode>)],
    columns: usize,
    icons: IconSource,
) -> String {
    let mut out = String::from(HEADER);
    if profiles.is_empty() {
        // Not a valid page list without an entry, so keep it an empty list.
        out.push_str("[]\n");
        return out;
    }
    // Dynacat derives the URL from the name: keep the names apart.
    let mut used: Vec<String> = Vec::new();
    for (name, nodes) in profiles {
        let mut unique = name.clone();
        let mut n = 1;
        while used.contains(&unique.to_lowercase()) {
            n += 1;
            unique = format!("{name} ({n})");
        }
        used.push(unique.to_lowercase());
        profile_page(&mut out, &unique, columns, nodes, icons);
    }
    out
}

/// Depth-first: the folder's own bookmarks become one group, then each
/// subfolder follows.
fn collect(
    kids: &BTreeMap<&str, Vec<&WireNode>>,
    folder: &WireNode,
    path: Option<&str>,
    depth: usize,
    style: &Style,
    groups: &mut Groups,
) {
    let children = kids
        .get(folder.id.as_str())
        .map(Vec::as_slice)
        .unwrap_or(&[]);
    let mut links = own_links(children);
    // At the depth limit the folders below join this group.
    let merge = style.depth.is_some_and(|d| depth >= d);
    if merge {
        fn all(
            kids: &BTreeMap<&str, Vec<&WireNode>>,
            id: &str,
            left: usize,
            out: &mut Vec<(String, String)>,
        ) {
            if left == 0 {
                return;
            }
            for c in kids.get(id).map(Vec::as_slice).unwrap_or(&[]) {
                if c.kind == Kind::Folder {
                    let kids_of = kids.get(c.id.as_str()).map(Vec::as_slice).unwrap_or(&[]);
                    out.extend(own_links(kids_of));
                    all(kids, &c.id, left - 1, out);
                }
            }
        }
        all(kids, &folder.id, MAX_DEPTH - depth, &mut links);
    }
    if !links.is_empty() {
        groups.push((path.map(str::to_string), links));
    }
    if merge || depth >= MAX_DEPTH {
        return;
    }
    for c in children.iter().filter(|c| c.kind == Kind::Folder) {
        let name = match c.title.trim() {
            "" => "(unnamed)",
            n => n,
        };
        let sub = match (path, style.names) {
            (Some(p), GroupNames::Path) => format!("{p} / {name}"),
            _ => name.to_string(),
        };
        collect(kids, c, Some(&sub), depth + 1, style, groups);
    }
}

/// The http(s) bookmarks among `children`, as `(title, url)`.
fn own_links(children: &[&WireNode]) -> Vec<(String, String)> {
    children
        .iter()
        .filter(|c| c.kind == Kind::Bookmark)
        .filter_map(|c| {
            let url = c.url.as_deref()?.trim();
            let lower = url.to_ascii_lowercase();
            if !(lower.starts_with("http://") || lower.starts_with("https://")) {
                return None;
            }
            let title = if c.title.trim().is_empty() {
                url
            } else {
                c.title.trim()
            };
            Some((title.to_string(), url.to_string()))
        })
        .collect()
}

/// `https://host[:port]/favicon.ico` for a http(s) URL.
fn icon_url(url: &str) -> Option<String> {
    let (scheme, rest) = url.split_once("://")?;
    let host = rest.split(['/', '?', '#']).next()?;
    // Credentials in the URL must never end up in a second URL.
    if host.is_empty() || host.contains('@') {
        return None;
    }
    Some(format!("{scheme}://{host}/favicon.ico"))
}

/// A YAML double-quoted scalar. JSON string syntax is valid YAML, and
/// quoting everything keeps `yes`, `1e3`, `#` and `: ` from being misread.
fn scalar(s: &str) -> String {
    // JSON leaves these unescaped, but YAML rejects DEL and folds the
    // Unicode line breaks.
    let json = serde_json::to_string(s).expect("strings serialise");
    let mut out = String::with_capacity(json.len());
    for c in json.chars() {
        match c {
            '\u{7f}' | '\u{85}' | '\u{2028}' | '\u{2029}' => {
                out.push_str(&format!("\\u{:04x}", c as u32))
            }
            c => out.push(c),
        }
    }
    out
}

